# --- найпростіший вивід ------------------------------------------------
print("Привіт!")

# --- кілька значень через кому ----------------------------------------
# print сам ставить пробіл між значеннями
print("Тиск:", 101325, "Па")

# --- параметр sep: чим розділяти значення ------------------------------
print("a", "b", "c", sep="-")        # a-b-c
print(2026, 9, 8, sep=".")           # 2026.9.8

# --- параметр end: чим завершити рядок ---------------------------------
# за замовчуванням end="\n" — перехід на новий рядок
print("Ціна:", end=" ")
print(500)                            # Ціна: 500

# --- повторення рядка --------------------------------------------------
print("-" * 30)

