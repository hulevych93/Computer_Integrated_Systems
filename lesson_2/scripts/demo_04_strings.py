"""Заняття 2 · Демонстрація 4. Рядки.

Розглядаємо: створення рядків, f-рядки, методи, індекси та зрізи.
"""

# --- створення рядків --------------------------------------------------
s = "Гулевич"
first = 'Михайло'                # лапки можуть бути будь-які, головне парні

print(len(s))                     # 7    довжина
print(s + " " + first)            # конкатенація
print("-" * 20)                   # повторення

# лапки всередині рядка
print("він сказав \"так\"")
print('він сказав "так"')

# перехід на новий рядок усередині одного рядка
print("рядок 1\nрядок 2")

# --- f-рядки: головний інструмент виводу -------------------------------
x = 2 / 3

print(f"Привіт, {first}!")
print(f"{x}")                     # 0.6666666666666666
print(f"{x:.3f}")                 # 0.667    три знаки після коми
print(f"{x:.1%}")                 # 66.7%    у відсотках

# всередині f-рядка можна виконувати обчислення
print(f"Периметр: {2 * (8.5 + 6.2):.2f} м")

# --- методи рядків -----------------------------------------------------
text = "  Hello World  "

print(text.strip())               # "Hello World"   прибирає пробіли по краях
print(text.upper())               # великі літери
print(text.lower())               # малі літери
print(text.replace("World", "Python"))
print(text.count("l"))            # 3

print("a,b,c".split(","))         # ['a', 'b', 'c']
print("Гулевич".startswith("Г"))  # True

# ВАЖЛИВО: методи не змінюють початковий рядок, а повертають новий
text.upper()                      # сам text не змінився
text = text.upper()               # тепер змінився

# --- індекси та зрізи --------------------------------------------------
w = "Python"
#     P  y  t  h  o  n
#     0  1  2  3  4  5      індекс
#    -6 -5 -4 -3 -2 -1      індекс з кінця

print(w[0])                       # 'P'      перший символ
print(w[-1])                      # 'n'      останній символ
print(w[0:3])                     # 'Pyt'    від 0 до 3, права межа не входить
print(w[:3])                      # 'Pyt'    від початку
print(w[3:])                      # 'hon'    до кінця
print(w[::-1])                    # 'nohtyP' у зворотному порядку

# =======================================================================
# ЗАВДАННЯ 4 (виконуємо на парі)
# =======================================================================
# 1) запитати ПІБ одним рядком
# 2) прибрати зайві пробіли, вивести великими літерами
# 3) вивести кількість символів
# 4) вивести ініціали у вигляді "Г. М. В."

full_name = input("Введіть ПІБ: ").strip()

print(full_name.upper())
print("Символів:", len(full_name))

parts = full_name.split()         # список слів: ['Гулевич', 'Михайло', 'Володимирович']

initials = parts[0][0] + ". " + parts[1][0] + ". " + parts[2][0] + "."
print("Ініціали:", initials)

# те саме коротше, через f-рядок:
print(f"Ініціали: {parts[0][0]}. {parts[1][0]}. {parts[2][0]}.")
