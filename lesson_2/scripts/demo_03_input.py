# K  = °C + 273.15
# °F = 1.8 * °C + 32

t_c = float(input("Температура, °C: ").replace(",", "."))

t_k = t_c + 273.15
t_f = 1.8 * t_c + 32

print(f"{t_c:.3f} °C = {t_k:.3f} K")
print(f"{t_c:.3f} °C = {t_f:.3f} °F")

