# --- два числові типи --------------------------------------------------
n = 25                        # int   — ціле
t = 36.6                      # float — дійсне

print(type(n))                # <class 'int'>
print(type(t))                # <class 'float'>

# --- арифметичні операції ----------------------------------------------
print(7 + 2)                  # 9
print(7 - 2)                  # 5
print(7 * 2)                  # 14
print(7 / 2)                  # 3.5    звичайне ділення — завжди float
print(7 // 2)                 # 3      ціла частина від ділення
print(7 % 2)                  # 1      остача від ділення
print(2 ** 10)                # 1024   піднесення до степеня

print(type(8 / 2))            # <class 'float'>  — навіть коли ділиться націло

# --- перетворення типів ------------------------------------------------
print(int("7"))               # 7      рядок -> ціле
print(float("3.5"))           # 3.5    рядок -> дійсне
print(str(25))                # "25"   число -> рядок
print(float(7))               # 7.0

# int відкидає дробову частину, а НЕ округлює
print(int(3.9))               # 3
print(round(3.9))             # 4
print(round(3.456, 2))        # 3.46

