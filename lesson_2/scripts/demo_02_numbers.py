# 1) задати змінними довжину і ширину аудиторії в метрах
# 2) обчислити площу та периметр
# 3) вивести результати з точністю 2 знаки після коми
# 4) додатково: скільки цілих столів 1.2 м x 0.6 м уміститься за площею

length = 8.5
width = 6.2

area = length * width
perimeter = 2 * (length + width)

print(f"Площа:    {area:.2f} м2")
print(f"Периметр: {perimeter:.2f} м")

table_area = 1.2 * 0.6
tables = int(area // table_area)
print("Столів за площею:", tables)

