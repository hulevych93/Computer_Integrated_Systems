"""Заняття 3 · Демонстрація 4. Контроль технологічного параметра."""

# --- КРОК 1. Уставки ---------------------------------------------------
ABSOLUTE_ZERO = -273.15    # фізична межа
T_MIN = -40.0              # нижня межа робочого діапазону
T_MAX = 60.0               # верхня межа робочого діапазону
T_ALARM = 100.0            # аварійна уставка
NEAR_LIMIT = 5.0           # зона наближення до межі

# --- КРОК 2. Ввід даних ------------------------------------------------
name = input("Назва параметра: ").strip()
unit = input("Одиниця виміру: ").strip()
t = float(input("Виміряне значення: ").replace(",", "."))

# --- КРОК 3. Валідація -------------------------------------------------
if t < ABSOLUTE_ZERO:
    print(f"Помилка: значення нижче абсолютного нуля ({ABSOLUTE_ZERO} °C)")
else:
    # --- КРОК 4. Визначення стану --------------------------------------
    if t >= T_ALARM:
        state = "АВАРІЯ"
    elif T_MIN <= t <= T_MAX:
        state = "НОРМА"
    else:
        state = "ПОПЕРЕДЖЕННЯ"

    # --- КРОК 5. Підсумковий вивід -------------------------------------
    print(f"{name}: {t:.1f} {unit} — {state}")

    # --- Додатково: наближення до межі ---------------------------------
    if state == "НОРМА" and t > T_MAX - NEAR_LIMIT:
        print(f"Увага: наближення до верхньої межі {T_MAX:.1f} {unit}")
