"""Заняття 3 · Демонстрація 3. Розгалуження if / elif / else."""

T_MIN = -40.0
T_MAX = 60.0
T_ALARM = 100.0

t = float(input("Температура, °C: ").replace(",", "."))

# --- КРОК 1. Просто if -------------------------------------------------
if t > T_MAX:
    print("Перевищення верхньої межі")

print("Кінець перевірки")      # виводиться завжди — рядок поза умовою

print("-" * 40)

# --- КРОК 2. Додаємо else ----------------------------------------------
if T_MIN <= t <= T_MAX:
    print("Параметр у нормі")
else:
    print("Параметр поза діапазоном")

print("-" * 40)

# --- КРОК 3. Чотири стани через elif -----------------------------------
# Порядок перевірок: від найвужчої умови до найширшої
if t < T_MIN:
    print("Нижче робочого діапазону")
elif t <= T_MAX:
    print("Норма")
elif t < T_ALARM:
    print("Попередження")
else:
    print("Аварія")

# --- КРОК 4. Перевірка всіх гілок --------------------------------------
# Контрольні значення: -50, 20, 80, 150

print("-" * 40)

# --- КРОК 5. Вибір за значенням: match / case --------------------------
# match доречний тоді, коли порівнюємо одне значення з переліком
# конкретних варіантів. Для діапазонів залишається if / elif.

code = input("Код стану (N/W/A): ").strip().upper()

match code:
    case "N":
        print("Норма")
    case "W" | "P":            # кілька значень в одному варіанті
        print("Попередження")
    case "A":
        print("Аварія")
    case _:                    # аналог else
        print("Невідомий код")
