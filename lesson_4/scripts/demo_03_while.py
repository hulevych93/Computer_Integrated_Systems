# =====================================================================
# 3. Перепит некоректного значення
# =====================================================================
# Минулого заняття ми могли лише повідомити про помилку.
# Тепер можемо вимагати правильне значення.
#
#   t = float(input("Температура, °C: "))
#   while t < -273.15:
#       print("Нижче абсолютного нуля!")
#       t = float(input("Повторіть: "))
#   print("Прийнято:", t)
#
# Перевіряємо: -300, -500, 20

tries = 0
t = float(input("Температура, °C: "))
tries += 1

while t < -273.15:
    print("Нижче абсолютного нуля!")
    t = float(input("Повторіть: "))
    tries += 1

print("Прийнято:", t, " °C з ", tries, " спроби")

