"""Заняття 4 · Демонстрація 4. Звіт про серію вимірювань.
"""


T_MIN = -40.0
T_MAX = 60.0

n = int(input("Скільки вимірювань: "))

summ = 0

i = 0
out_of_allowed_range = 0

t_max = 0
t_min = 0

while i < n:
    t = float(input("Наступне вимірювання: "))

    summ += t

    if t < T_MIN or t > T_MAX:
        print("Поза допуском!")
        out_of_allowed_range += 1

    if t > t_max:
        t_max = t

    if t < t_min:
        t_min = t

    i += 1

mean = summ / n

print("Вимірювань: ", n)
print("Середнє: ", mean, " °C")
print("Мінімум: ", t_min, " °C")
print("Максимум: ", t_max, " °C")
print("Поза допуском: ", out_of_allowed_range, " з ", n)

