def classify(value, lo, hi, alarm):
    """Повертає стан параметра за уставками."""
    if value >= alarm:
        return "АВАРІЯ"
    if lo <= value <= hi:
        return "НОРМА"
    return "ПОПЕРЕДЖЕННЯ"


