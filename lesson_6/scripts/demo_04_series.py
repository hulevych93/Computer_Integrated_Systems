# Описати функцію filter_range(values, lo, hi), яка повертає новий
# список лише зі значень у межах [lo, hi].
#
# Перевірка:
#   filter_range([10, 70, 30], 0, 50)  ->  [10, 30]

data = [10, 70, 30, 100, 5, 500]

def filter_range(data, lo, hi):
    data1 = []
    for value in data:
        if value > lo and value < hi:
            data1.append(value)
    return data1

def filter_out_of_range(data, lo, hi):
    data1 = []
    for value in data:
        if not (value > lo and value < hi):
            data1.append(value)
    return data1

print(data)
print(filter_range(data, 0, 50))
print(filter_out_of_range(data, 0, 50))

